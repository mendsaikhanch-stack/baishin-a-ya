-- 1. Enable RLS
alter table public.content_articles enable row level security;

-- 2. Public SELECT policy for published rows (idempotent — duplicate-safe)
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'content_articles'
      and policyname = 'Public can read published content articles'
  ) then
    create policy "Public can read published content articles"
      on public.content_articles
      for select
      to anon, authenticated
      using (published = true);
  end if;
end $$;

