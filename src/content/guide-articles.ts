export function getArticleBySlug(slug: string): GuideArticle | undefined {
  return GUIDE_ARTICLES.find((a) => a.slug === slug)
}

export type CategoryGroup = {
  category: GuideCategory
  title: string
  icon: string
  articles: GuideArticle[]
}

export function groupByCategory(): CategoryGroup[] {
  const order: GuideCategory[] = [
    'before_starting',
    'land_selection',
    'budget_planning',
    'material_selection',
    'foundation',
    'seasonal_timing',
  ]
  return order.map((category) => ({
    category,
    title: CATEGORY_META[category].title,
    icon: CATEGORY_META[category].icon,
    articles: GUIDE_ARTICLES.filter((a) => a.category === category),
  }))
}

/** Serialize an article to plain text for DB content (AI retrieval). */
export function articleToPlainText(article: GuideArticle): string {
  const lines: string[] = [article.title, '', article.summary, '']
  for (const s of article.sections) {
    if (s.heading) lines.push(`## ${s.heading}`)
    if (s.body) for (const p of s.body) lines.push(p)
    if (s.bullets) for (const b of s.bullets) lines.push(`- ${b}`)
    lines.push('')
  }
  return lines.join('\n').trim()
}
